.section .text
.globl _start

_start:

# ============================================================
# 1. BEQ PRIS
# ============================================================

    li   x1, 10
    li   x2, 10

    beq  x1, x1, beq_taken

    # Cette instruction NE DOIT PAS être exécutée
    li   x3, 0x11111111

beq_taken:
    li   x3, 0x22222222


# ============================================================
# 2. JAL
# ============================================================

    jal  x5, jal_target

    # Cette instruction NE DOIT PAS être exécutée
    li   x6, 0x33333333

jal_target:
    li   x6, 0x44444444

    # x5 doit contenir l'adresse de retour
    # (PC de l'instruction suivant le JAL)


# ============================================================
# 3. JALR
# ============================================================

    la   x7, jalr_target
    jalr x8, 0(x7)

    # Cette instruction NE DOIT PAS être exécutée
    li   x9, 0x55555555

jalr_target:
    li   x9, 0x66666666

    # x8 = adresse de retour


# ============================================================
# 4. LUI
# ============================================================

    lui  x10, 0x12345

    # x10 = 0x12345000


# ============================================================
# 5. AUIPC
# ============================================================

    auipc x11, 0x1

    # x11 = PC de l'AUIPC + 0x1000


# ============================================================
# 6. SRA AVEC NOMBRE NEGATIF
# ============================================================

    li   x12, -16

    li   x13, 2

    sra  x14, x12, x13

    # -16 >> 2 = -4
    # x14 = 0xFFFFFFFC


# ============================================================
# 7. SLT AVEC NOMBRES NEGATIFS
# ============================================================

    li   x15, -10
    li   x16, -5

    slt  x17, x15, x16

    # -10 < -5 → x17 = 1

    slt  x18, x16, x15

    # -5 < -10 → x18 = 0


# ============================================================
# 8. SLT AVEC NEGATIF / POSITIF
# ============================================================

    li   x19, -1
    li   x20, 1

    slt  x21, x19, x20

    # -1 < 1 → x21 = 1

    slt  x22, x20, x19

    # 1 < -1 → x22 = 0


# ============================================================
# 9. STORE / LOAD BYTE
# ============================================================

    li   x23, 0x12345678

    # Adresse mémoire = 0x100
    li   x24, 0x100

    sw   x23, 0(x24)

    # Mémoire :
    #
    # 0x100 = 0x78
    # 0x101 = 0x56
    # 0x102 = 0x34
    # 0x103 = 0x12
    #
    # Little endian


    lb   x25, 0(x24)

    # 0x78 = 120 positif
    # x25 = 0x00000078


    lbu  x26, 0(x24)

    # x26 = 0x00000078


# ============================================================
# 10. LOAD BYTE SIGNE NEGATIF
# ============================================================

    li   x27, 0x00000080

    sb   x27, 4(x24)

    lb   x28, 4(x24)

    # 0x80 interprété comme signed byte = -128
    # x28 = 0xFFFFFF80


    lbu  x29, 4(x24)

    # unsigned → 128
    # x29 = 0x00000080


# ============================================================
# 11. STORE / LOAD HALF
# ============================================================

    li   x30, 0x0000ABCD

    sh   x30, 8(x24)

    lh   x31, 8(x24)

    # 0xABCD interprété comme signed 16 bits
    # x31 = 0xFFFFABCD


# ============================================================
# 12. LOAD HALF UNSIGNED
# ============================================================

    lhu  x2, 8(x24)

    # x2 = 0x0000ABCD


# ============================================================
# FIN
# ============================================================

end:
    beq  x0, x0, end
